BEGIN;
ALTER TYPE "Role" RENAME TO "Role_old";
CREATE TYPE "Role" AS ENUM ('SUPER_ADMIN', 'REVIEWER', 'UNIT');
ALTER TABLE "User" ALTER COLUMN "role" TYPE "Role" USING (
  CASE "role"::text
    WHEN 'SATKER' THEN 'UNIT'
    WHEN 'TIM_PENILAI_MARVEL' THEN 'REVIEWER'
    WHEN 'TIM_PENILAI_ITJEN' THEN 'REVIEWER'
    ELSE "role"::text
  END
)::"Role";
DROP TYPE "Role_old";
UPDATE "UsulinSignature" SET "role" = CASE
  WHEN "role" = 'SATKER' THEN 'UNIT'
  WHEN "role" IN ('TIM_PENILAI_MARVEL', 'TIM_PENILAI_ITJEN') THEN 'REVIEWER'
  ELSE "role" END;
COMMIT;
